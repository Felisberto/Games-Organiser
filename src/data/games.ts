//  backlog. Tudo aqui é um array (lista) de objetos. Cada objeto é um jogo.
//
//  ═══════════════════════════════════════════════════════════════════════
//  COMO ADICIONAR UM JOGO NOVO
//  ═══════════════════════════════════════════════════════════════════════
//  1. Vá até o final da lista GAMES abaixo (procure por "FIM DA LISTA").
//  2. Copie qualquer bloco { ... } inteiro (de uma chave { até a } que fecha).
//  3. Cole abaixo do último jogo, ANTES do colchete ] que fecha a lista.
//  4. Mude os campos para o novo jogo (título, capa, status, nota, etc.).
//  5. Salve o arquivo. O site atualiza sozinho.
//
//  ═══════════════════════════════════════════════════════════════════════
//  COMO ALTERAR O STATUS DE UM JOGO
//  ═══════════════════════════════════════════════════════════════════════
//  Encontre o jogo, troque o campo "status" por um destes 5 valores:
//
//     "jogando"      → Está jogando agora
//     "finalizado"   → Zerou / completou
//     "visitado"     → Jogou um pouco mas não dedicou
//     "estocado"     → Na fila (backlog), ainda não começou
//     "adiado"       → Começou mas pausou sem previsão de voltar
//
//  ═══════════════════════════════════════════════════════════════════════
//  REFERÊNCIA DE CAMPOS (o que cada campo significa)
//  ═══════════════════════════════════════════════════════════════════════
//  id            texto     identificador único (sem espaços, ex: "elden-ring")
//  title         texto     título completo do jogo
//  cover         texto     link (URL) da capa em formato caixa (retrato ~3:4)
//  releaseDate   texto     data de lançamento "AAAA-MM-DD" (ex: 2022-02-25)
//  status        texto     um dos 5 status acima
//  hoursPlayed   número    total de horas jogadas
//  playMinutes   número    minutos extras (0-59). Opcional, padrão 0.
//  playSeconds   número    segundos extras (0-59). Opcional, padrão 0.
//                             → o tempo aparece como "Xh Ym Zs" no card
//  studio        texto     nome da desenvolvedora / estúdio
//  studioAvatar  texto     link (URL) do logo quadrado da desenvolvedora
//  genres        lista     gêneros (estilo Steam). Ex: ["Ação", "Mundo Aberto"].
//                             Sugestões: Ação, Aventura, RPG, Estratégia, Simulação,
//                             Corrida, Esporte, Casual, Indie, Mundo Aberto, Terror,
//                             Souls-like, Roguelike, FPS, Plataforma, Quebra-cabeça,
//                             Sobrevivência, Cartas, Por Turnos, CRPG, Metroidvania,
//                             Point & Click, Visual Novel, Real-Time Strategy, MMO,
//                             Faroeste, Sci-Fi, Fantasia, Mitologia, Cyberpunk, Noir,
//  startDate     texto     data que você começou "AAAA-MM-DD" (vazio = não começou)
//  endDate       texto     data que você terminou "AAAA-MM-DD"
//                             → use null se ainda não terminou
//  rating        número    SUA nota: 0 a 10 normal, ou 15 = Perpétuo (god-tier)
//  difficulty    texto     dificuldade do jogo. Um destes 5 valores:
//                             "muito-facil"  → Muito Fácil
//                             "facil"        → Fácil
//                             "medio"        → Médio
//                             "dificil"      → Difícil
//                             "muito-dificil" → Muito Difícil
//                             → deixe sem o campo (ou string vazia) para esconder
//  topRank       número    posição no seu Top 10 pessoal (manual, ignora nota).
//                             Use 1 = #1 melhor, 2 = #2, etc. Até 10.
//                             → deixe sem o campo (ou 0) para não incluir no Top 10
//  platforms     lista     lojas onde o jogo está disponível. Cada item é:
//                             { name: "Steam", icon: "steam",
//                               url: "link completo da loja" }
//                             → "icon" agora é uma chave: "steam", "xbox",
//                               "playstation", ou "nintendo" (sem aspas duplas
//                               extras — é um valor fixo, não URL)
//                             → deixe como [] (vazio) se não quiser mostrar
//                             → "url" é o link da loja — bote "" se ainda não
//                               tiver e preencha depois
//  playedOn      lista     EM QUAIS VIDEOGAMES você jogou (texto livre). Ex:
//                             ["PS4", "PC", "PS2", "SNES", "3DS"]
//                             → pode botar qualquer console: PS1, PS2, PS3, PS4,
//                               PS5, Xbox 360, SNES, Mega Drive, 3DS, Switch, PC…
//                             → deixe como [] (vazio) se não quiser mostrar
//  recomendadoPor texto     QUEM recomendou o jogo (opcional). Ex: "Eu",
//                             "@viewername", "Felipe", etc.
//                             → se você mesmo escolheu, bote "Eu"
//                             → deixe sem o campo (ou string vazia) para esconder
// ============================================================================

export type GameStatus = 'jogando' | 'finalizado' | 'visitado' | 'estocado' | 'adiado';

export type GameDifficulty =
  | 'muito-facil'
  | 'facil'
  | 'medio'
  | 'dificil'
  | 'muito-dificil'
  | 'repetitivo'
  | 'grinding'
  | 'relaxante'
  | 'estrategico'
  | 'caotico';

export type PlatformKey = 'steam' | 'xbox' | 'playstation' | 'nintendo';

export interface PlatformLink {
  name: string;
  icon: PlatformKey;
  url: string;
}

